/**
 * Checks the run target is an open issue on the session's branch, ensures a
 * spec exists (committing a stub when planning left none) and records
 * `ctx.specDir`. Whether the issue is somebody's child does not matter: its
 * label put it in this flow. Claiming it is the run's lifecycle, not this
 * step's.
 */
import { access, mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { existingSpecDirName, SousError, specDirName, type RunFn } from "sous-factory";

export const SPEC_HEADINGS = ["Problem Statement", "Solution", "User Stories", "Implementation Decisions", "Testing Decisions", "Out of Scope", "Further Notes"] as const;

/** `spec.md` for a spec-less issue: the body under Problem Statement, placeholders elsewhere. */
export const specStub = (issue: { ref: string; title: string; body: string }): string => {
  const sections = SPEC_HEADINGS.map((heading) => {
    const content = heading === "Problem Statement" && issue.body.trim().length > 0 ? issue.body.trim() : `_Not specified; see issue ${issue.ref}._`;
    return `## ${heading}\n\n${content}\n`;
  });
  return `# ${issue.title}\n\nGenerated by sous from issue ${issue.ref}.\n\n${sections.join("\n")}`;
};

const exists = (path: string): Promise<boolean> =>
  access(path).then(
    () => true,
    () => false,
  );

export default (async (ctx) => {
  // The spec folder `sous run` derived from the specsDir setting, relative to the repository root.
  const specsDir = dirname(ctx.specDir);
  const { id } = ctx.issue;

  const issue = await ctx.tracker.getIssue(id);
  if (issue.state !== "open") throw new SousError(`init: ${issue.ref} is ${issue.state}; sous runs open issues only`);
  const checkedOut = await ctx.git.currentBranch(ctx.worktree);
  if (checkedOut !== ctx.branch) throw new SousError(`init: the worktree is on ${checkedOut}, the session expects ${ctx.branch}`);

  const entries = await readdir(join(ctx.worktree, specsDir)).catch(() => [] as string[]);
  const specDir = join(specsDir, existingSpecDirName(entries, id) ?? specDirName(id, issue.title));
  const spec = join(specDir, "spec.md");
  let sha: string | undefined;
  if (!(await exists(join(ctx.worktree, spec)))) {
    await mkdir(join(ctx.worktree, specDir), { recursive: true });
    await writeFile(join(ctx.worktree, spec), specStub(issue), "utf8");
    await ctx.git.add(ctx.worktree, [spec]);
    sha = await ctx.git.commit(ctx.worktree, `spec(${issue.ref}): stub from issue`);
  }

  ctx.specDir = specDir;
  return {
    summary: sha === undefined ? `init: using ${spec}` : `init: created ${spec} from the issue and committed it`,
    commits: sha === undefined ? [] : [sha],
    output: { specDir },
  };
}) satisfies RunFn;
