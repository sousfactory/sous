import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { BRANCH, ctxOf, fakeGit, fakeTracker, issue } from "sous-factory/testing";
import init, { SPEC_HEADINGS, specStub } from "../../steps/init/run.js";

describe("specStub", () => {
  it("puts the issue body under Problem Statement and placeholders under the other headings", () => {
    const stub = specStub({ ref: "#7", title: "Add thing", body: "  We need a thing.\n" });
    expect(stub.startsWith("# Add thing\n\nGenerated by sous from issue #7.\n\n## Problem Statement\n\nWe need a thing.\n")).toBe(true);
    for (const heading of SPEC_HEADINGS) expect(stub).toContain(`## ${heading}\n`);
    expect(stub.match(/_Not specified; see issue #7\._/g)).toHaveLength(SPEC_HEADINGS.length - 1);
  });

  it("falls back to the placeholder for an empty body", () => {
    expect(specStub({ ref: "#7", title: "t", body: "  " })).toContain("## Problem Statement\n\n_Not specified; see issue #7._");
  });
});

describe("init", () => {
  let worktree: string;
  beforeEach(async () => {
    worktree = await mkdtemp(join(tmpdir(), "sous-init-"));
  });
  afterEach(() => rm(worktree, { recursive: true, force: true }));

  it("creates the spec stub in the worktree, commits it and records specDir; the issue is left to the lifecycle", async () => {
    const f = ctxOf({ worktree, issue: { id: "1", ref: "#1", title: "Test issue", body: "Do the thing" } });
    const out = await init(f.ctx);

    expect(out).toEqual({ summary: "init: created specs/1-test-issue/spec.md from the issue and committed it", commits: ["sha1"], output: { specDir: "specs/1-test-issue" } });
    expect(await readFile(join(worktree, "specs/1-test-issue/spec.md"), "utf8")).toContain("# Test issue\n\nGenerated by sous from issue #1.\n\n## Problem Statement\n\nDo the thing\n");
    expect(f.git.calls).toEqual([`currentBranch(${worktree})`, `add(${worktree}, specs/1-test-issue/spec.md)`, `commit(${worktree}, spec(#1): stub from issue)`]);
    expect(f.tracker.issues.get("1")?.labels).toEqual([]);
    expect(f.tracker.claims).toEqual([]);
    expect(f.ctx.specDir).toBe("specs/1-test-issue");
  });

  it("uses the planned spec folder by issue prefix, leaves it alone and commits nothing", async () => {
    await mkdir(join(worktree, "specs/1-planned-name"), { recursive: true });
    await writeFile(join(worktree, "specs/1-planned-name/spec.md"), "# Planned\n");
    const f = ctxOf({ worktree });
    const out = await init(f.ctx);

    expect(out).toEqual({ summary: "init: using specs/1-planned-name/spec.md", commits: [], output: { specDir: "specs/1-planned-name" } });
    expect(await readFile(join(worktree, "specs/1-planned-name/spec.md"), "utf8")).toBe("# Planned\n");
    expect(f.git.calls).toEqual([`currentBranch(${worktree})`]);
    expect(f.ctx.specDir).toBe("specs/1-planned-name");
  });

  it("refuses a closed issue", async () => {
    const f = ctxOf({ worktree, issue: { id: "1", state: "closed" } });
    await expect(init(f.ctx)).rejects.toThrow("init: #1 is closed; sous runs open issues only");
    expect(f.git.calls).toEqual([]);
  });

  it("runs a sub-issue like any other: its label put it in the flow", async () => {
    const tracker = fakeTracker({ issues: [issue({ id: "5" }), issue({ id: "1" })], subIssues: { "5": ["1"] } });
    const f = ctxOf({ worktree, tracker });
    expect((await init(f.ctx)).output).toEqual({ specDir: "specs/1-issue-1" });
  });

  it("refuses a worktree on another branch", async () => {
    const f = ctxOf({ worktree, git: fakeGit({ existing: ["main", BRANCH] }) });
    await expect(init(f.ctx)).rejects.toThrow(`init: the worktree is on main, the session expects ${BRANCH}`);
  });

  it("looks for the spec folder beside ctx.specDir, which sous run derives from the specsDir setting", async () => {
    await mkdir(join(worktree, "docs/specs/1-planned-name"), { recursive: true });
    await writeFile(join(worktree, "docs/specs/1-planned-name/spec.md"), "# Planned\n");
    const f = ctxOf({ worktree, specDir: "docs/specs/1-test-issue" });
    expect(await init(f.ctx)).toMatchObject({ commits: [], output: { specDir: "docs/specs/1-planned-name" } });
  });
});
